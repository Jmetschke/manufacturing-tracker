// Day editor lifecycle, validation, save feedback, and conflict recovery.
function buildSchedulePayload(includeTasks = true) {
  const events = getEventValues();
  validateEvents(events);

  const tasks = includeTasks
    ? getScheduleTaskValues("#scheduleTaskRows .schedule-task-row")
    : [];
  const processingTasks = includeTasks ? getProcessingTaskValues() : [];

  const invalidTask = [...tasks, ...processingTasks].find(task =>
    (!task.autoGenerated && task.totalHours <= 0) ||
    task.assignments.reduce((sum, assignment) => sum + assignment.hours, 0) > task.totalHours
  );
  if (invalidTask) {
    throw new Error("Each manually entered task needs total hours, and assigned person hours cannot exceed the task total.");
  }

  const testPickups = includeTasks ? getTestPickupValues() : [];
  const invalidPickup = testPickups.find(pickup => !/^([01]\d|2[0-3]):[0-5]\d$/.test(pickup.time) || !pickup.items.length);
  if (invalidPickup) {
    throw new Error("Each Test Pick Up needs a valid HH:MM time and at least one selected item.");
  }

  return JSON.stringify({
    ...scheduleEditorBasePayload,
    batchHijnx: getBatchValues("hijnx"),
    batchSb: getBatchValues("sb"),
    events,
    tasks,
    testPickups,
    processingTasks
  });
}

let scheduleDaySavePending = false;
let scheduleEditorBaseRevision = "missing";
let scheduleEditorBasePayload = {};
let adminCalendarLoadSequence = 0;

function setScheduleSaveStatus(text, type = "") {
  const status = document.getElementById("scheduleSaveStatus");
  status.textContent = text;
  status.className = type ? `message ${type}` : "message";
}

function editScheduleDay(isoDate) {
  if (scheduleDaySavePending) return;
  setScheduleSaveStatus("");
  document.getElementById("scheduleReloadButton").hidden = true;
  scheduleEditorBaseRevision = adminScheduleRevisions.get(isoDate) || "missing";
  const payload = parseSchedulePayload(adminScheduleRows.get(isoDate));
  scheduleEditorBasePayload = payload;
  const isWeekendDay = isWeekendIsoDate(isoDate);
  const taskSections = document.querySelectorAll(".schedule-task-section, .pickup-group, .processing-group");

  document.getElementById("schedule_edit_date").value = isoDate;
  document.getElementById("scheduleEditLabel").textContent = formatDisplayDate(isoDate);
  populateEventRows(payload.events);
  populateBatchRows("hijnx", payload.batchHijnx);
  populateBatchRows("sb", payload.batchSb);
  taskSections.forEach(section => {
    section.hidden = isWeekendDay;
  });
  populateScheduleTaskRows(isWeekendDay ? "" : adminScheduleRows.get(isoDate) || "");
  populateTestPickupRows(isWeekendDay ? [] : payload.testPickups);
  populateScheduleTaskRows(isWeekendDay ? [] : payload.processingTasks, "processingTaskRows", false);
  if (!isWeekendDay) {
    syncGeneratedBatchTasksFromBatches();
  }
  document.getElementById("scheduleEditor").classList.add("active");
  showMessage("");
  getBatchRows("hijnx").querySelector(".batch-input").focus();
}

function cancelScheduleEdit() {
  if (scheduleDaySavePending) return;
  document.getElementById("scheduleEditor").classList.remove("active");
  document.getElementById("schedule_edit_date").value = "";
  document.getElementById("eventRows").innerHTML = "";
  getBatchRows("hijnx").innerHTML = "";
  getBatchRows("sb").innerHTML = "";
  document.getElementById("scheduleTaskRows").innerHTML = "";
  document.getElementById("testPickupRows").innerHTML = "";
  document.getElementById("processingTaskRows").innerHTML = "";
  const planner = document.getElementById("batchTaskPlanner");
  if (planner) {
    planner.innerHTML = "";
    planner.hidden = true;
  }
  document.querySelectorAll(".schedule-task-section, .pickup-group, .processing-group").forEach(section => {
    section.hidden = false;
  });
}

async function reloadScheduleEditor() {
  if (scheduleDaySavePending) return;
  if (!confirm("Discard your unsaved edits and load the latest saved version of this day?")) return;
  const date = document.getElementById("schedule_edit_date").value;
  scheduleDaySavePending = true;
  setScheduleSaveStatus("Loading saved day…");
  try {
    const response = await adminFetch(`/schedule?from=${date}&to=${date}`, { cache: "no-store" });
    if (!response.ok) throw new Error(await response.text());
    const row = (await response.json()).find(row => row.schedule_date === date);
    adminCalendarLoadSequence++;
    if (row) {
      adminScheduleRows.set(date, row.tasks);
      adminScheduleRevisions.set(date, row.revision);
    } else {
      adminScheduleRows.delete(date);
      adminScheduleRevisions.delete(date);
    }
    scheduleDaySavePending = false;
    editScheduleDay(date);
  } catch (err) { setScheduleSaveStatus(`Could not reload: ${err.message}`, "error"); }
  finally { scheduleDaySavePending = false; }
}

async function saveScheduleDay() {
  if (scheduleDaySavePending) return;
  const scheduleDate = document.getElementById("schedule_edit_date").value;
  if (!scheduleDate) return;
  let tasks;
  try {
    tasks = buildSchedulePayload(!isWeekendIsoDate(scheduleDate));
  } catch (err) {
    setScheduleSaveStatus(err.message, "error");
    return;
  }

  scheduleDaySavePending = true;
  const editor = document.getElementById("scheduleEditor");
  const saveButton = document.getElementById("scheduleSaveButton");
  const controls = Array.from(editor.querySelectorAll("button, input, select, textarea"))
    .map(control => ({ control, disabled: control.disabled }));
  controls.forEach(({ control }) => { control.disabled = true; });
  editor.setAttribute("aria-busy", "true");
  saveButton.textContent = "Saving…";
  setScheduleSaveStatus("Saving calendar day…");
  let saved = false;

  try {
    const res = await adminFetch(`/admin/schedule/${scheduleDate}`, {
      method: "PUT",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ tasks, base_revision: scheduleEditorBaseRevision })
    });
    if (!res.ok) throw Object.assign(new Error(await res.text() || `Request failed (${res.status})`), { status: res.status });
    const result = await res.json();
    // Use the authoritative response, including server-assigned event IDs.
    adminCalendarLoadSequence++; // Ignore an older in-flight calendar refresh.
    adminScheduleRows.set(scheduleDate, result.tasks);
    adminScheduleRevisions.set(scheduleDate, result.revision);
    saved = true;
  } catch (err) {
    document.getElementById("scheduleReloadButton").hidden = false;
    if (err.status === 409 || err.status === 428) {
      setScheduleSaveStatus(`${err.message} Your unsaved edits remain below.`, "error");
    } else setScheduleSaveStatus(`Could not confirm the save: ${err.message}. Your edits are still here. If the connection dropped, refresh the calendar before retrying.`, "error");
  } finally {
    scheduleDaySavePending = false;
    controls.forEach(({ control, disabled }) => { control.disabled = disabled; });
    editor.removeAttribute("aria-busy");
    saveButton.textContent = "Save Day";
  }

  if (saved) {
    cancelScheduleEdit();
    showMessage("Calendar day updated.", "success");
    try {
      const gridStart = dateOnly(adminCalendarStartDate);
      const rows = Array.from(adminScheduleRows, ([schedule_date, tasks]) => ({ schedule_date, tasks }));
      adminActiveScheduleByDate = buildAdminActiveScheduleByDate(rows, gridStart, addDays(gridStart, 41));
      renderAdminCalendar(gridStart);
    } catch (err) {
      showMessage("Calendar day saved, but the display could not refresh. Reopen the Calendar tab to reload it.", "error");
      console.error("Calendar render after save failed", err);
    }
  }
}

